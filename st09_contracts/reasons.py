    CALIBRATION_REVISION_MISMATCH = "CALIBRATION_REVISION_MISMATCH"
    MAP_REVISION_MISMATCH = "MAP_REVISION_MISMATCH"
    INVALID_STAMP = "INVALID_STAMP"
