"""Qualified atlas pairs consumed in the operation's current carrying scene.

Atlas status/quality ranks proposals only. Native exact-target refinement and
online connection validate both stored seeds; the endpoint service still checks
its own actual entry/contact/exit targets, followed by full-chain certification.
"""
from dataclasses import asdict, replace
import hashlib
import json
import math
from pathlib import Path

from scipy.spatial.transform import Rotation
from luggage_description.scene_tf_config_utils import load_scene_tf_config, world_transform
from luggage_planning.atlas.proposals import AtlasProposalReader, AtlasQualification, refine_atlas_pairs
from luggage_planning.joint_operation.planner import JointSeedHint
from luggage_planning.placement_prior.contracts import Transform


def load_operation_atlas(npz_path,yaml_path,receipt_path,scene_path,*,robot_description,
                         model_sha256,scene_revision,world_from_container):
    """Only an explicitly reviewed byte-bound receipt can enable an artifact.

    MD5 here reproduces the existing builder's dependency identifiers; the
    artifact bytes and complete runtime model remain SHA256-bound separately.
    No receipt is generated by this loader, even when old hashes happen to match.
    """
    record=json.loads(Path(receipt_path).read_text())
    if (set(record)!={'qualification','model_sha256','scene_revision'}
            or record['model_sha256']!=model_sha256 or record['scene_revision']!=scene_revision):
        raise ValueError('atlas reviewed runtime identity mismatch')
    source=AtlasQualification(**record['qualification'])
    if (source.urdf_hash!=hashlib.md5(robot_description.encode()).hexdigest()
            or source.scene_tf_hash!=hashlib.md5(Path(scene_path).read_bytes()).hexdigest()):
        raise ValueError('atlas runtime dependency bytes mismatch')
    xyz,rpy=world_transform(load_scene_tf_config(scene_path),'container_link')
    configured=Transform(tuple(float(v) for v in xyz),tuple(float(v) for v in Rotation.from_euler('xyz',rpy).as_quat()))
    if (any(abs(a-b)>1e-9 for a,b in zip(configured.translation,world_from_container.translation))
            or abs(sum(a*b for a,b in zip(configured.quaternion_xyzw,world_from_container.quaternion_xyzw)))<1.-1e-12):
        raise ValueError('atlas current container transform mismatch')
    reader=AtlasProposalReader(npz_path,yaml_path,source)
    if reader.atlas is None:raise ValueError(reader.reason)
    return reader


class AtlasOperationHints:
    def __init__(self,reader,ik,connections,*,scene_revision,model_sha256,
                 operation_geometry_hash,
                 max_refinement_s=1.,fallback_time_fraction=.5):
        if reader.atlas is None or reader.source is None:
            raise ValueError('qualified reader required')
        if (not math.isfinite(max_refinement_s) or not 0<max_refinement_s<=10
                or not math.isfinite(fallback_time_fraction) or not .5<=fallback_time_fraction<1.):
            raise ValueError('bounded atlas work and at least half remaining time for online fallback required')
        self.reader,self.ik,self.connections=reader,ik,connections
        self.scene_revision,self.model_sha256=scene_revision,model_sha256
        # The sampler's geometry MD5 describes its legacy bounds block. The
        # operation scene uses the normalized hull SHA256. The loader already
        # binds the sampler to exact scene bytes; callers derive this hash from
        # those same admitted bytes, never by comparing different hash domains.
        if not isinstance(operation_geometry_hash,str) or not operation_geometry_hash:
            raise ValueError('operation normalized geometry identity required')
        self.operation_geometry_hash=operation_geometry_hash
        self.max_refinement_s,self.fallback_time_fraction=max_refinement_s,fallback_time_fraction

    def augment(self,candidate,*,request_id,deadline,cancelled,clock):
        scene=candidate.scenes.carry
        source=self.reader.source
        if ((scene.scene_revision,scene.model_hash,scene.geometry_hash)!=
                (self.scene_revision,self.model_sha256,self.operation_geometry_hash)):
            return candidate,(('atlas','ATLAS_CURRENT_IDENTITY_MISMATCH'),)
        def query(world_tool):
            target=scene.world_from_container.inverse().compose(world_tool)
            x=target.compose(Transform((1.,0.,0.),(0.,0.,0.,1.))).translation
            yaw=math.atan2(x[1]-target.translation[1],x[0]-target.translation[0])%(2*math.pi)
            return self.reader.query(*target.translation,yaw)
        G=candidate.world_from_pick_box.inverse().compose(candidate.world_from_pick_tool)
        contact=query(candidate.world_from_settled_box.compose(G))
        release=query(candidate.world_from_release_tool)
        # All metrics/sample targets remain diagnostics, never validity gates.
        trace=[('atlas_contact',asdict(contact)),('atlas_release',asdict(release))]
        began=clock()
        refine_deadline=min(deadline,began+min(self.max_refinement_s,
            max(0.,deadline-began)*(1.-self.fallback_time_fraction)))
        trace.append(('atlas_budget',self.max_refinement_s,self.fallback_time_fraction,refine_deadline))
        # Endpoint service accepts at most three hints. Keep original branch IDs
        # and pairing while bounding extra native work under the shared deadline.
        release=replace(release,branches=release.branches[:3])
        checked=set()
        sequence=0
        def refine(target,seed,**kwargs):
            nonlocal sequence
            sequence+=1
            result=self.ik.refine(scene,target,seed,request_id=request_id+':atlas-ik:'+str(sequence),**kwargs)
            trace.append(('atlas_ik',sequence,result.reason))
            if result.success and result.complete:
                checked.add(result.joints)
                return result.joints
            return None
        def check_carrying(q,**kwargs):
            # refine() already performed full native bounds/FK/collision checks
            # on these exact scene bytes and q, not a rigid-tool approximation.
            return tuple(q) in checked
        def connect(start,goal,**kwargs):
            return self.connections.connect(scene,start,goal,request_id=request_id+':atlas-pair:'+str(sequence),**kwargs)
        refined=refine_atlas_pairs(release,expected_source=source,
            exact_contact_world=candidate.world_from_release_tool,
            world_from_container=scene.world_from_container,refine=refine,
            check_carrying=check_carrying,connect=connect,deadline=refine_deadline,
            cancelled=cancelled,clock=clock)
        trace.append(('atlas_pairs',refined.reason,refined.trace))
        hints=[JointSeedHint('atlas-pair:'+p.branch_id,p.transit_joints) for p in refined.pairs]
        if not hints:
            hints=[JointSeedHint('atlas-contact:'+branch,q) for branch,q in refined.contact_options]
        if clock()>=deadline or cancelled():return candidate,tuple(trace)
        return replace(candidate,place_entry_seeds=tuple(hints[:3])),tuple(trace)
